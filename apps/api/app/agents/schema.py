"""Structured output every agent must return. Validated before anything is stored."""

from typing import Literal

from pydantic import BaseModel, Field


class AgentFinding(BaseModel):
    title: str = Field(description="Short name of the risk, at most 12 words.")
    description: str = Field(
        description="What could go wrong, why, and what it would cost. 2 to 4 sentences."
    )
    evidence_type: Literal["fact", "assumption", "estimate", "ai_hypothesis"] = Field(
        description=(
            "fact: stated in the decision or the answers. assumption: taken as true without "
            "verification. estimate: a quantity you derived. ai_hypothesis: plausible but "
            "generated by you, to be checked."
        )
    )
    basis: str = Field(
        description="What in the decision supports this finding, or 'none' if it rests on "
        "general knowledge only."
    )
    likelihood: int = Field(
        description="1 rare, 2 unlikely, 3 possible, 4 likely, 5 almost certain."
    )
    impact: int = Field(
        description="1 negligible, 2 minor, 3 moderate, 4 major, 5 critical for the organisation."
    )
    mitigation: str = Field(description="One concrete action that reduces this risk.")


class AgentReport(BaseModel):
    summary: str = Field(description="Your overall reading of the decision, 2 to 4 sentences.")
    confidence: Literal["low", "medium", "high"] = Field(
        description="How much the available information lets you conclude."
    )
    findings: list[AgentFinding] = Field(description="Between 2 and 6 risks, most serious first.")
    missing_information: list[str] = Field(
        description="Up to 5 facts that would most change your assessment if known."
    )


class FindingReview(BaseModel):
    ref: int = Field(description="Number of the finding being reviewed, as listed.")
    verdict: Literal["supported", "weak", "unsupported"] = Field(
        description=(
            "supported: the finding follows from the decision as written. weak: plausible but "
            "thinly supported, to be checked. unsupported: contradicted by the decision or "
            "resting on an invented fact."
        )
    )
    evidence_type: Literal["fact", "assumption", "estimate", "ai_hypothesis"] = Field(
        description="The correct evidence type. Change it if the agent mislabelled the finding."
    )
    note: str = Field(description="One sentence explaining the verdict.")


class AuditReport(BaseModel):
    summary: str = Field(description="Overall quality of the agents' work, 2 to 3 sentences.")
    reviews: list[FindingReview] = Field(description="One review per finding listed.")
