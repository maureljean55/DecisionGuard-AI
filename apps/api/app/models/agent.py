"""Agent runs and their findings. Tenant data, protected by RLS."""

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import DateTime, ForeignKey, Integer, SmallInteger, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import UUIDPrimaryKey, utcnow
from app.db.session import Base


class EvidenceType(StrEnum):
    """How well-founded a statement is. Shown next to every finding."""

    FACT = "fact"  # stated in the decision brief or the answers
    ASSUMPTION = "assumption"  # taken as true, not verified
    ESTIMATE = "estimate"  # a quantity derived by reasoning, not supplied
    AI_HYPOTHESIS = "ai_hypothesis"  # plausible, generated by the model, to be checked


class AgentRun(UUIDPrimaryKey, Base):
    __tablename__ = "agent_runs"

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE")
    )
    analysis_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("analyses.id", ondelete="CASCADE"), index=True
    )
    agent: Mapped[str] = mapped_column(String(32))
    status: Mapped[str] = mapped_column(String(16))  # completed | failed
    provider: Mapped[str] = mapped_column(String(32))
    model: Mapped[str | None] = mapped_column(String(64))
    summary: Mapped[str | None] = mapped_column(Text)
    confidence: Mapped[str | None] = mapped_column(String(8))  # low | medium | high
    missing_information: Mapped[list[str]] = mapped_column(JSONB, default=list)
    input_tokens: Mapped[int] = mapped_column(Integer, default=0)
    output_tokens: Mapped[int] = mapped_column(Integer, default=0)
    duration_ms: Mapped[int] = mapped_column(Integer, default=0)
    error_code: Mapped[str | None] = mapped_column(String(64))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class Finding(UUIDPrimaryKey, Base):
    __tablename__ = "findings"

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE")
    )
    analysis_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("analyses.id", ondelete="CASCADE"), index=True
    )
    agent_run_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("agent_runs.id", ondelete="CASCADE"))
    agent: Mapped[str] = mapped_column(String(32))
    position: Mapped[int] = mapped_column(Integer)
    title: Mapped[str] = mapped_column(String(200))
    description: Mapped[str] = mapped_column(Text)
    evidence_type: Mapped[str] = mapped_column(String(16))
    basis: Mapped[str] = mapped_column(Text)
    likelihood: Mapped[int] = mapped_column(SmallInteger)  # 1..5, as assessed by the agent
    impact: Mapped[int] = mapped_column(SmallInteger)  # 1..5, as assessed by the agent
    mitigation: Mapped[str] = mapped_column(Text)
    # Set by the audit agent: supported | weak | unsupported (excluded from the risk score).
    audit_status: Mapped[str | None] = mapped_column(String(16))
    audit_note: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
